// pdfExport.js — PDF export utility for the Contract Nutrition Label
//
// Generates a plain-text PDF representation of the nutrition label data
// without any third-party PDF library dependency. The output is a minimal,
// standards-compliant PDF 1.4 document that any PDF viewer can open.
//
// Usage:
//   const { buildPdfBytes, downloadPdf } = require('./pdfExport');
//   const bytes = buildPdfBytes(metrics, { functionName: 'transfer', costStroops: 12345 });
//   downloadPdf(bytes, 'my-contract-nutrition.pdf');

'use strict';

const SOROBAN_LIMITS_XLM = 10_000_000; // stroops per XLM

// ── Low-level PDF helpers ─────────────────────────────────────────────────────

/**
 * Encode a UTF-8 string as a PDF literal string, escaping special characters.
 * @param {string} str
 * @returns {string}
 */
function pdfLiteral(str) {
  return (
    '(' +
    String(str)
      .replace(/\\/g, '\\\\')
      .replace(/\(/g, '\\(')
      .replace(/\)/g, '\\)')
      .replace(/\r/g, '\\r')
      .replace(/\n/g, '\\n') +
    ')'
  );
}

/**
 * Build a cross-reference table entry.
 * @param {number} offset byte offset
 * @returns {string}
 */
function xrefEntry(offset) {
  return `${String(offset).padStart(10, '0')} 00000 n \r\n`;
}

// ── Content builders ─────────────────────────────────────────────────────────

/**
 * Build the PDF page content stream for the nutrition label.
 *
 * @param {import('./nutritionLabel').NutritionMetric[]} metrics
 * @param {{ functionName?: string, costStroops?: number, generatedAt?: string }} options
 * @returns {string} raw PDF content stream bytes (Latin-1 safe)
 */
function buildContentStream(metrics, options) {
  const { functionName = 'transaction', costStroops, generatedAt = new Date().toISOString() } = options || {};

  const lines = [];

  // Helper to push a text-drawing command
  const text = (x, y, size, str) => {
    lines.push(`BT /F1 ${size} Tf ${x} ${y} Td ${pdfLiteral(str)} Tj ET`);
  };

  const textBold = (x, y, size, str) => {
    lines.push(`BT /F2 ${size} Tf ${x} ${y} Td ${pdfLiteral(str)} Tj ET`);
  };

  // Horizontal rule helper (x1, y, x2)
  const rule = (x1, y, x2, width = 1) => {
    lines.push(`${width} w ${x1} ${y} m ${x2} ${y} l S`);
  };

  const PAGE_WIDTH = 595; // A4 width in pt
  const LEFT = 50;
  const RIGHT = PAGE_WIDTH - 50;
  const COL_VALUE = RIGHT - 140;
  const COL_LIMIT = RIGHT - 70;
  const COL_PCT = RIGHT;

  let y = 780;

  // ── Masthead ──
  textBold(LEFT, y, 22, 'Nutrition Facts');
  y -= 6;
  rule(LEFT, y, RIGHT, 3);
  y -= 14;
  text(LEFT, y, 9, `1 transaction  (${functionName})`);
  y -= 4;
  rule(LEFT, y, RIGHT, 1);
  y -= 16;

  textBold(LEFT, y, 10, 'Amount Per Transaction');
  y -= 14;

  // Find peak metric
  const peak = metrics.reduce((max, m) => Math.max(max, m.percent), 0);
  const peakStr = peak > 0 && peak < 0.1 ? '<0.1%' : `${peak.toFixed(1)}%`;
  textBold(LEFT, y, 11, `Peak Resource Load`);
  textBold(COL_PCT - 20, y, 14, peakStr);
  y -= 6;
  rule(LEFT, y, RIGHT, 8);
  y -= 14;

  text(COL_PCT - 60, y, 8, '% Budget');
  y -= 4;
  rule(LEFT, y, RIGHT, 1);
  y -= 14;

  // Column headers for breakdown table
  text(LEFT, y, 8, 'Resource');
  text(COL_VALUE, y, 8, 'Used');
  text(COL_LIMIT, y, 8, 'Limit');
  text(COL_PCT, y, 8, '%');
  y -= 4;
  rule(LEFT, y, RIGHT, 0.5);
  y -= 12;

  // ── Metric rows ──
  for (const metric of metrics) {
    const pct = metric.percent > 0 && metric.percent < 0.1 ? '<0.1%' : `${metric.percent.toFixed(1)}%`;
    const used = formatCompact(metric.value);
    const limit = formatCompact(metric.limit);

    if (metric.bold) {
      textBold(LEFT, y, 9, metric.label);
    } else {
      text(LEFT + 10, y, 9, metric.label);
    }
    text(COL_VALUE, y, 9, used);
    text(COL_LIMIT, y, 9, limit);
    text(COL_PCT, y, 9, pct);
    y -= 4;
    rule(LEFT, y, RIGHT, 0.3);
    y -= 12;
  }

  y -= 4;
  rule(LEFT, y, RIGHT, 4);
  y -= 14;

  // ── Gas breakdown ──
  if (typeof costStroops === 'number' && costStroops > 0) {
    const xlm = (costStroops / SOROBAN_LIMITS_XLM).toFixed(7);
    textBold(LEFT, y, 9, 'Total Resource Fee');
    text(COL_PCT - 40, y, 9, `${xlm} XLM`);
    y -= 14;
  }

  // ── Footnote ──
  y -= 8;
  rule(LEFT, y, RIGHT, 2);
  y -= 12;
  text(LEFT, y, 7, '* % Budget = share of the Soroban per-transaction resource limit consumed by this call.');
  y -= 10;
  text(LEFT, y, 7, `  Generated by Sky Moon Scope on ${generatedAt.slice(0, 19).replace('T', ' ')} UTC`);

  return lines.join('\n');
}

/**
 * Compact number formatter (mirrors nutritionLabel.js formatValue).
 * Kept local so pdfExport has no runtime dependency on nutritionLabel.
 *
 * @param {number} value
 * @returns {string}
 */
function formatCompact(value) {
  const n = typeof value === 'number' && Number.isFinite(value) && value >= 0 ? value : 0;
  if (n >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(1)}B`;
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1)}M`;
  if (n >= 1_000) return `${(n / 1_000).toFixed(1)}K`;
  return String(Math.round(n));
}

// ── PDF document assembly ─────────────────────────────────────────────────────

/**
 * Assemble a minimal PDF 1.4 document and return it as a Uint8Array.
 *
 * The document is one A4 page using the standard Helvetica and
 * Helvetica-Bold Type1 fonts (built into every PDF viewer) so no font
 * embedding is required.
 *
 * @param {import('./nutritionLabel').NutritionMetric[]} metrics
 * @param {{ functionName?: string, costStroops?: number, generatedAt?: string }} [options]
 * @returns {Uint8Array}
 */
function buildPdfBytes(metrics, options) {
  if (!Array.isArray(metrics) || metrics.length === 0) {
    throw new Error('buildPdfBytes: metrics must be a non-empty array');
  }

  const contentStream = buildContentStream(metrics, options);
  const streamBytes = new TextEncoder().encode(contentStream);
  const streamLen = streamBytes.length;

  // ── Object bodies ──
  //   1: Catalog
  //   2: Pages tree
  //   3: Page
  //   4: Font F1 (Helvetica)
  //   5: Font F2 (Helvetica-Bold)
  //   6: Content stream

  const obj1 = '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n';
  const obj2 = '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n';
  const obj3 =
    '3 0 obj\n' +
    '<< /Type /Page /Parent 2 0 R\n' +
    '   /MediaBox [0 0 595 842]\n' +
    '   /Contents 6 0 R\n' +
    '   /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >>\n' +
    '>>\nendobj\n';
  const obj4 =
    '4 0 obj\n' +
    '<< /Type /Font /Subtype /Type1\n' +
    '   /BaseFont /Helvetica\n' +
    '   /Encoding /WinAnsiEncoding\n' +
    '>>\nendobj\n';
  const obj5 =
    '5 0 obj\n' +
    '<< /Type /Font /Subtype /Type1\n' +
    '   /BaseFont /Helvetica-Bold\n' +
    '   /Encoding /WinAnsiEncoding\n' +
    '>>\nendobj\n';
  const obj6Header = `6 0 obj\n<< /Length ${streamLen} >>\nstream\n`;
  const obj6Footer = '\nendstream\nendobj\n';

  // ── Calculate byte offsets for xref ──
  const header = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n'; // magic + binary comment
  let offset = header.length;

  const offsets = [];
  const objects = [obj1, obj2, obj3, obj4, obj5];

  for (const obj of objects) {
    offsets.push(offset);
    offset += new TextEncoder().encode(obj).length;
  }

  // object 6 (stream)
  const obj6HeaderBytes = new TextEncoder().encode(obj6Header);
  const obj6FooterBytes = new TextEncoder().encode(obj6Footer);
  offsets.push(offset);
  offset += obj6HeaderBytes.length + streamBytes.length + obj6FooterBytes.length;

  const xrefOffset = offset;

  // ── xref table ──
  const xref =
    'xref\n' +
    `0 7\n` +
    '0000000000 65535 f \r\n' +
    offsets.map(xrefEntry).join('');

  const trailer =
    'trailer\n' +
    `<< /Size 7 /Root 1 0 R >>\n` +
    'startxref\n' +
    `${xrefOffset}\n` +
    '%%EOF\n';

  // ── Assemble all parts ──
  const enc = new TextEncoder();
  const parts = [
    enc.encode(header),
    enc.encode(obj1),
    enc.encode(obj2),
    enc.encode(obj3),
    enc.encode(obj4),
    enc.encode(obj5),
    obj6HeaderBytes,
    streamBytes,
    obj6FooterBytes,
    enc.encode(xref),
    enc.encode(trailer),
  ];

  const totalLength = parts.reduce((sum, p) => sum + p.length, 0);
  const result = new Uint8Array(totalLength);
  let pos = 0;
  for (const part of parts) {
    result.set(part, pos);
    pos += part.length;
  }

  return result;
}

/**
 * Trigger a browser download of the generated PDF.
 *
 * Safe to call in any browser environment; no-ops in Node.js (test env).
 *
 * @param {Uint8Array} pdfBytes
 * @param {string} [filename]
 */
function downloadPdf(pdfBytes, filename) {
  if (typeof document === 'undefined') return; // Node.js / SSR guard
  const blob = new Blob([pdfBytes], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename || `nutrition-label-${Date.now()}.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

module.exports = { buildPdfBytes, downloadPdf, buildContentStream, formatCompact };
